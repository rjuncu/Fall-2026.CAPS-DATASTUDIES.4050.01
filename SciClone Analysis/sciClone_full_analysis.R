# Function definition for creating datasets that fit sciclone restrictions
# Parameters: 
# patient_id -> variable representing one eligible patient with primary and metastatic tumors
# sciclone_mutation_table -> matrix of information regarding patients
make_sciclone_vafs <- function(patient_id, sciclone_mutation_table) {
  
  patient_data <- sciclone_mutation_table %>%
    filter(`Patient ID` == patient_id)
  
  primary <- patient_data %>%
    filter(`Sample Type` == "Primary") %>%
    transmute(
      chr = Chromosome,
      st = Start_Position,
      ref = t_ref_count,
      var = t_alt_count,
      vaf = VAF * 100,
      depth = t_ref_count + t_alt_count
    )
  
  metastasis <- patient_data %>%
    filter(`Sample Type` == "Metastasis") %>%
    transmute(
      chr = Chromosome,
      st = Start_Position,
      ref = t_ref_count,
      var = t_alt_count,
      vaf = VAF * 100,
      depth = t_ref_count + t_alt_count
    )
  
  list(
    primary = primary,
    metastasis = metastasis
  )
}

# Function definition for retrieving sample names
# Parameters: 
# patient_id -> variable representing one eligible patient with primary and metastatic tumors
# sciclone_mutation_table -> matrix of information regarding patients
get_sample_names <- function(patient_id, sciclone_mutation_table){
  sciclone_mutation_table %>%
    filter(`Patient ID`== patient_id) %>%
    distinct(`Sample Type`, Tumor_Sample_Barcode) %>%
    arrange(
      factor(
        `Sample Type`,
        levels = c("Primary", "Metastasis")
      )
    ) %>%
    pull(Tumor_Sample_Barcode)
}

# Function definition for adjusting the maximum clusters variable based on number of shared mutations 
# Parameters: 
# vafs -> matrix of VAF data
# minimumDepth -> The amount of reads required, standard = 100
# requested_max -> The default amount of maximum clusters for this analysis 
get_max_clusters <- function(vafs, minimumDepth = 100, requested_max = 5) {
  usable_sites <- Reduce(
    intersect,
    lapply(vafs, function(x) {
      paste(x$chr, x$st, sep = ":")[x$depth >= minimumDepth]
    })
  )
  n_usable <- length(usable_sites)
  
  if (n_usable < 3) {
    return(NA_integer_)
  }
  return(min(requested_max, n_usable - 1))
}

# Function definition for applying sciclone clustering onto patients
# Parameters: 
# sciclone_patient_table -> table containing patients with over 100 depth and 3 shared mutations
# sciclone_mutation_table -> high dimensional data containing mutation info on tumors 
run_sciclone <- function(sciclone_patient_table, sciclone_mutation_table) {
  
  run_summary <- list()
  results <- list()
  
  for (patient_id in sciclone_patient_table$`Patient ID`) {
    
    cat("Running SciClone for patient:", patient_id, "\n")
    
    vafs <- make_sciclone_vafs(patient_id, sciclone_mutation_table)
    vafs <- lapply(vafs, as.data.frame)
    
    sample_names <- get_sample_names(patient_id, sciclone_mutation_table)
    
    usable_sites <- Reduce(
      intersect,
      lapply(vafs, function(x) {
        paste(x$chr, x$st, sep = ":")[x$depth >= 100]
      })
    )
    
    n_usable_sites <- length(usable_sites)
    
    max_clusters <- get_max_clusters(
      vafs = vafs,
      minimumDepth = 100,
      requested_max = 5
    )
    
    # Skip patients with too few usable sites
    if (is.na(max_clusters)) {
      cat("SKIPPED:", patient_id, "\n")
      
      run_summary[[patient_id]] <- data.frame(
        Patient_ID = patient_id,
        Status = "SKIPPED",
        Usable_sites = n_usable_sites,
        Maximum_clusters = NA_integer_,
        Error = "Fewer than three usable sites"
      )
      
      next
    }
    
    # Run SciClone
    sciClone_result <- tryCatch(
      {
        sciClone(
          vafs = vafs,
          sampleNames = sample_names,
          minimumDepth = 100,
          maximumClusters = max_clusters,
          clusterMethod = "binomial.bmm",
          clusterParams =
            "no.min.items.condition no.apply.overlapping.std.dev.condition no.uncertainty.overlap.detection"
        )
      },
      error = function(e) {
        cat("FAILED:", patient_id, "\n")
        cat("Error:", conditionMessage(e), "\n")
        NULL
      }
    )
    
    # Record failures and skip the success block
    if (is.null(sciClone_result)) {
      run_summary[[patient_id]] <- data.frame(
        Patient_ID = patient_id,
        Status = "FAILED",
        Usable_sites = n_usable_sites,
        Maximum_clusters = max_clusters,
        Error = "SciClone failed; see console output"
      )
      
      next
    }
    
    # Store successful result
    results[[patient_id]] <- sciClone_result
    
    saveRDS(
      sciClone_result,
      file = paste0(
        "sciclone_results/objects/",
        patient_id,
        "_sciclone.rds"
      )
    )
    
    run_summary[[patient_id]] <- data.frame(
      Patient_ID = patient_id,
      Status = "SUCCESS",
      Usable_sites = n_usable_sites,
      Maximum_clusters = max_clusters,
      Error = NA_character_
    )
    
    cat("Finished:", patient_id, "\n")
  }
  
  # Return both objects to the calling environment
  return(list(
    run_summary = run_summary,
    results = results)
  )
}

